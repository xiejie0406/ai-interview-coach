CREATE TABLE aps_task_dependency (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    predecessor_task_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    successor_task_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    dependency_type VARCHAR(16) NOT NULL DEFAULT 'FINISH',
    threshold_qty DECIMAL(18,6) NULL,
    threshold_ratio DECIMAL(8,6) NULL,
    transfer_batch_qty DECIMAL(18,6) NULL,
    uom_code VARCHAR(16) NULL,
    lag_seconds INT UNSIGNED NOT NULL DEFAULT 0,
    consumes_output TINYINT UNSIGNED NOT NULL DEFAULT 0,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_by VARCHAR(64) NULL,
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(64) NULL,
    row_version BIGINT UNSIGNED NOT NULL DEFAULT 0,
    CONSTRAINT pk_task_dependency PRIMARY KEY (id),
    CONSTRAINT uk_task_dependency UNIQUE (predecessor_task_id, successor_task_id),
    CONSTRAINT fk_task_dep_predecessor FOREIGN KEY (predecessor_task_id) REFERENCES aps_task (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_task_dep_successor FOREIGN KEY (successor_task_id) REFERENCES aps_task (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_task_dep_distinct CHECK (predecessor_task_id <> successor_task_id),
    CONSTRAINT ck_task_dep_type CHECK (dependency_type IN ('FINISH', 'QUANTITY', 'SAME_START')),
    CONSTRAINT ck_task_dep_threshold CHECK ((dependency_type = 'FINISH' AND threshold_qty IS NULL AND threshold_ratio IS NULL AND transfer_batch_qty IS NULL AND uom_code IS NULL) OR (dependency_type = 'QUANTITY' AND ((threshold_qty IS NOT NULL AND threshold_ratio IS NULL AND threshold_qty > 0 AND uom_code IS NOT NULL) OR (threshold_qty IS NULL AND threshold_ratio IS NOT NULL AND threshold_ratio > 0 AND threshold_ratio <= 1))) OR (dependency_type = 'SAME_START' AND threshold_qty IS NULL AND threshold_ratio IS NULL AND transfer_batch_qty IS NULL AND uom_code IS NULL AND lag_seconds = 0 AND consumes_output = 0)),
    CONSTRAINT ck_task_dep_transfer CHECK (transfer_batch_qty IS NULL OR (transfer_batch_qty > 0 AND uom_code IS NOT NULL)),
    CONSTRAINT ck_task_dep_consume CHECK (consumes_output IN (0, 1)),
    KEY idx_task_dep_predecessor (predecessor_task_id),
    KEY idx_task_dep_successor (successor_task_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='M17 任务依赖；SAME_START 仅冻结来源且 P0 阻断执行';


CREATE TABLE aps_order (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    order_no VARCHAR(64) NOT NULL,
    source_system VARCHAR(32) NOT NULL DEFAULT 'LOCAL',
    external_id VARCHAR(128) NULL,
    customer_code VARCHAR(64) NULL,
    customer_name VARCHAR(128) NULL,
    priority SMALLINT NOT NULL DEFAULT 50,
    promised_at DATETIME(3) NULL,
    earliest_start_at DATETIME(3) NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    remark VARCHAR(500) NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_by VARCHAR(64) NULL,
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(64) NULL,
    row_version BIGINT UNSIGNED NOT NULL DEFAULT 0,
    CONSTRAINT pk_order PRIMARY KEY (id),
    CONSTRAINT uk_order_no UNIQUE (order_no),
    CONSTRAINT uk_order_external UNIQUE (source_system, external_id),
    CONSTRAINT ck_order_priority CHECK (priority BETWEEN 1 AND 100),
    CONSTRAINT ck_order_status CHECK (status IN ('DRAFT', 'RELEASED', 'IN_PRODUCTION', 'COMPLETED', 'CANCELLED')),
    KEY idx_order_due (status, promised_at, priority)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='M13 生产订单头';


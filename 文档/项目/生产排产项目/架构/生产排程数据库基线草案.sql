CREATE TABLE aps_route_edge (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    route_version_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    predecessor_node_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    successor_node_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    dependency_type VARCHAR(16) NOT NULL DEFAULT 'FINISH',
    threshold_qty DECIMAL(18,6) NULL,
    threshold_ratio DECIMAL(8,6) NULL,
    transfer_batch_qty DECIMAL(18,6) NULL,
    lag_seconds INT UNSIGNED NOT NULL DEFAULT 0,
    consumes_output TINYINT UNSIGNED NOT NULL DEFAULT 0,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_by VARCHAR(64) NULL,
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(64) NULL,
    row_version BIGINT UNSIGNED NOT NULL DEFAULT 0,
    CONSTRAINT pk_route_edge PRIMARY KEY (id),
    CONSTRAINT uk_route_edge UNIQUE (route_version_id, predecessor_node_id, successor_node_id),
    CONSTRAINT fk_route_edge_version FOREIGN KEY (route_version_id) REFERENCES aps_route_version (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_route_edge_predecessor FOREIGN KEY (route_version_id, predecessor_node_id) REFERENCES aps_route_node (route_version_id, id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_route_edge_successor FOREIGN KEY (route_version_id, successor_node_id) REFERENCES aps_route_node (route_version_id, id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_route_edge_distinct CHECK (predecessor_node_id <> successor_node_id),
    CONSTRAINT ck_route_edge_type CHECK (dependency_type IN ('FINISH', 'QUANTITY', 'SAME_START')),
    CONSTRAINT ck_route_edge_threshold CHECK ((dependency_type = 'FINISH' AND threshold_qty IS NULL AND threshold_ratio IS NULL AND transfer_batch_qty IS NULL) OR (dependency_type = 'QUANTITY' AND ((threshold_qty IS NOT NULL AND threshold_ratio IS NULL AND threshold_qty > 0) OR (threshold_qty IS NULL AND threshold_ratio IS NOT NULL AND threshold_ratio > 0 AND threshold_ratio <= 1))) OR (dependency_type = 'SAME_START' AND threshold_qty IS NULL AND threshold_ratio IS NULL AND transfer_batch_qty IS NULL AND lag_seconds = 0 AND consumes_output = 0)),
    CONSTRAINT ck_route_edge_transfer CHECK (transfer_batch_qty IS NULL OR transfer_batch_qty > 0),
    CONSTRAINT ck_route_edge_consume CHECK (consumes_output IN (0, 1)),
    KEY idx_route_edge_version (route_version_id),
    KEY idx_route_edge_predecessor (route_version_id, predecessor_node_id),
    KEY idx_route_edge_successor (route_version_id, successor_node_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='M12 路线节点依赖；SAME_START 仅保留来源且 P0 阻断执行';


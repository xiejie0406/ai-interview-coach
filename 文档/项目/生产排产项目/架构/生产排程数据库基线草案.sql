CREATE TABLE aps_workshop (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    workshop_code VARCHAR(64) NOT NULL,
    workshop_name VARCHAR(128) NOT NULL,
    manager_user_id VARCHAR(64) NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    remark VARCHAR(500) NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_by VARCHAR(64) NULL,
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(64) NULL,
    row_version BIGINT UNSIGNED NOT NULL DEFAULT 0,
    CONSTRAINT pk_workshop PRIMARY KEY (id),
    CONSTRAINT uk_workshop_code UNIQUE (workshop_code),
    CONSTRAINT ck_workshop_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='M01 车间；单站点下的组织根节点';

